import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

enum AppLanguage {
  turkish('tr', 'Türkçe', '🇹🇷', TextDirection.ltr),
  english('en', 'English', '🇬🇧', TextDirection.ltr),
  german('de', 'Deutsch', '🇩🇪', TextDirection.ltr),
  french('fr', 'Français', '🇫🇷', TextDirection.ltr),
  russian('ru', 'Русский', '🇷🇺', TextDirection.ltr),
  arabic('ar', 'العربية', '🇸🇦', TextDirection.rtl),
  indonesian('id', 'Bahasa Indonesia', '🇮🇩', TextDirection.ltr),
  spanish('es', 'Español', '🇪🇸', TextDirection.ltr),
  portuguese('pt', 'Português', '🇧🇷', TextDirection.ltr),
  japanese('ja', '日本語', '🇯🇵', TextDirection.ltr),
  hindi('hi', 'हिन्दी', '🇮🇳', TextDirection.ltr);

  const AppLanguage(this.code, this.nativeName, this.flag, this.direction);

  final String code;
  final String nativeName;
  final String flag;
  final TextDirection direction;

  static AppLanguage fromCode(String? code) {
    return AppLanguage.values.firstWhere(
      (lang) => lang.code == code,
      orElse: () => AppLanguage.turkish,
    );
  }
}

class LanguageController extends ChangeNotifier {
  LanguageController({AppLanguage initialLanguage = AppLanguage.turkish})
      : _current = initialLanguage;

  static const String _prefKey = 'app_language_code';
  AppLanguage _current;

  AppLanguage get current => _current;
  Locale get locale => Locale(_current.code);
  TextDirection get textDirection => _current.direction;

  static Future<LanguageController> load() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final code = prefs.getString(_prefKey);
      return LanguageController(initialLanguage: AppLanguage.fromCode(code));
    } catch (_) {
      return LanguageController();
    }
  }

  Future<void> setLanguage(AppLanguage language) async {
    if (_current == language) return;
    _current = language;
    notifyListeners();
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefKey, language.code);
    } catch (_) {}
  }
}

class DefaultLanguageController extends LanguageController {
  DefaultLanguageController() : super();
}

